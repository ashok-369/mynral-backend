import { body } from "express-validator";

// ============================================================
// ADMIN LOGIN VALIDATION
// ============================================================

export const adminLoginValidation = [
  body("email")
    .trim()
    .notEmpty()
    .withMessage("Email is required")
    .isEmail()
    .withMessage("Please provide a valid email address")
    .normalizeEmail(),

  body("password")
    .notEmpty()
    .withMessage("Password is required"),
];